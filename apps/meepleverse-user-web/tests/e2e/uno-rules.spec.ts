import { test, expect } from "@playwright/test";
const label = "Luật chơi UNO Cơ bản";
test("UNO guide opens from the basic catalog card, explains house rules and returns focus", async ({ page }, info) => {
  await page.goto("/");
  const card = page.locator('article[data-game-id="uno-basic"]');
  const trigger = card.getByRole("button", { name: label, exact: true });
  await trigger.click();
  const dialog = page.getByRole("dialog", { name: label, exact: true });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole("table")).toHaveAccessibleName("Thành phần bộ 108 lá");
  await expect(dialog.getByRole("row")).toHaveCount(8);
  await expect(dialog.getByRole("heading", { level: 3 })).toHaveCount(8);
  await expect(dialog).toContainText("76 lá số + 24 lá chức năng theo màu + 8 lá đen = 108 lá");
  await expect(dialog).toContainText("A +2 → B +4 → C +4 → D nhận 10 lá");
  await expect(dialog).toContainText("C chọn màu, rồi tới A. D không được chọn màu.");
  await expect(dialog).toContainText("không có thách thức +4");
  await expect(dialog).toContainText("Không cần người khác bắt");
  await expect(dialog).toContainText("chỉ được đánh chính lá vừa bốc");
  await page.screenshot({ path: info.outputPath("uno-guide-desktop.png") });
  const body = dialog.getByLabel("Nội dung hướng dẫn luật chơi");
  await body.evaluate(element => { element.scrollTop = element.scrollHeight; });
  await expect(dialog.getByRole("button", { name: "Đóng hướng dẫn luật chơi" })).toBeInViewport();
  await dialog.getByRole("button", { name: "Đã hiểu, vào bàn thôi" }).click();
  await expect(trigger).toBeFocused();
  await trigger.click();
  expect(await body.evaluate(element => element.scrollTop)).toBe(0);
  await page.keyboard.press("Escape");
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
  await expect(page).toHaveURL("http://localhost:3100/");
});
test("UNO guide is usable on mobile before joining, in lobby and during a game", async ({ page, browser }, info) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/games/uno-basic");
  await page.getByRole("button", { name: label, exact: true }).click();
  const dialog = page.getByRole("dialog", { name: label, exact: true });
  const box = (await dialog.boundingBox())!;
  expect(box.x).toBeGreaterThanOrEqual(0); expect(box.x + box.width).toBeLessThanOrEqual(375);
  expect(box.y).toBeGreaterThanOrEqual(0); expect(box.y + box.height).toBeLessThanOrEqual(812);
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("uno-guide-mobile.png") });
  await page.keyboard.press("Escape");
  await page.getByLabel("Mọi người gọi bạn là gì?").fill("Tai");
  await page.getByRole("button", { name: "Tạo phòng UNO" }).click();
  await expect(page.getByRole("heading", { name: "Đợi bạn, đủ vui." })).toBeVisible();
  await page.getByRole("button", { name: label, exact: true }).click();
  await expect(dialog).toBeVisible(); await page.keyboard.press("Escape");
  const context = await browser.newContext();
  try {
    const guest = await context.newPage(); await guest.goto(page.url());
    await guest.getByLabel("Mọi người gọi bạn là gì?").fill("Linh");
    await guest.getByRole("button", { name: "Vào phòng", exact: true }).click();
    await expect(page.getByText("Linh", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Bắt đầu ván", exact: true }).click();
    await expect(page.getByTestId("uno-board")).toBeVisible();
    await expect(page.getByRole("button", { name: label, exact: true })).toBeInViewport();
    await page.getByRole("button", { name: label, exact: true }).click();
    await expect(dialog).toBeVisible();
    await dialog.getByRole("button", { name: "Đóng hướng dẫn luật chơi" }).click();
    await expect(page.getByTestId("uno-board")).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  } finally { await context.close(); }
});
